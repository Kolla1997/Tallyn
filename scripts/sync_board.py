#!/usr/bin/env python3
"""Add missing ideas, auto-promote ideas, then mirror both GitHub Projects into Obsidian Kanban notes. GitHub is the source of truth.

  Tallyn Board (BOARD_NUMBER) → docs/05 Board/Board.md
  Tallyn Ideas (IDEAS_NUMBER) → docs/06 Ideas/Ideas Board.md

Before mirroring, open type:idea issues missing from Tallyn Ideas are added under 'New', and ideas in
Stage 'Promoted' are moved to Tallyn Board (see promote.py). --no-promote skips both.
Needs the gh CLI and scripts/board.env. Usage: python3 scripts/sync_board.py [--no-promote]
"""
import json, pathlib, subprocess, sys, datetime

ROOT = pathlib.Path(__file__).resolve().parent.parent
env = dict(l.split("=", 1) for l in (ROOT / "scripts/board.env").read_text().split() if "=" in l)

BOARDS = [
    ("BOARD_NUMBER", ["Backlog", "In Progress", "Review", "Blocked", "Done"], {"Done"}, "docs/05 Board/Board.md"),
    ("IDEAS_NUMBER", ["New", "Exploring", "Promoted", "Parked", "Rejected"], {"Promoted", "Parked", "Rejected"},
     "docs/06 Ideas/Ideas Board.md"),
]

def sync(key, columns, collapsed, dest):
    if key not in env:
        print(f"- skipped {dest} ({key} not in board.env)")
        return
    out = subprocess.run(["gh", "project", "item-list", env[key], "--owner", env["BOARD_OWNER"],
                          "--format", "json", "--limit", "500"], capture_output=True, text=True)
    if out.returncode:
        sys.exit(out.stderr)
    cols = {c: [] for c in columns}
    for it in json.loads(out.stdout).get("items", []):
        stage = next((v for k, v in it.items() if k.lower() == "stage"), None)
        c = it.get("content") or {}
        if stage and stage not in cols:
            print(f"! #{c.get('number', '?')} has unknown Stage '{stage}', shown under {columns[0]}. "
                  f"Add it to BOARDS in sync_board.py")
        stage = stage if stage in cols else columns[0]
        num = f"#{c['number']} " if c.get("number") else ""
        title = (c.get("title") or it.get("title") or "untitled").replace("[", "(").replace("]", ")")
        tags = " ".join("#" + l.replace(":", "/") for l in it.get("labels", []) or [])
        extra = " ".join(f"{k.title()}: {it[k]}" for k in ("impact", "effort") if it.get(k))
        link = f"[{num}{title}]({c['url']})" if c.get("url") else title
        done = stage in ("Done", "Promoted", "Rejected")
        cols[stage].append(" ".join(x for x in (f"- [{'x' if done else ' '}]", link, extra, tags) if x))
    lines = ["---", "", "kanban-plugin: board", "", "---", "",
             f"<!-- Generated by scripts/sync_board.py on {datetime.date.today()}. Edit on GitHub, not here -->", ""]
    for col, cards in cols.items():
        lines += [f"## {col}", ""] + (["**Complete**"] if col == "Done" else []) + cards + ["", ""]
    settings = {"kanban-plugin": "board", "list-collapse": [c in collapsed for c in columns]}
    lines += ["%% kanban:settings", "```", json.dumps(settings, separators=(",", ":")), "```", "%%", ""]
    path, text = ROOT / dest, "\n".join(lines)
    # Skip rewrites that would only change the date stamp, so automated runs don't commit daily noise.
    strip = lambda s: [l for l in s.splitlines() if not l.startswith("<!-- Generated")]
    if path.exists() and strip(path.read_text()) == strip(text):
        print(f"= {sum(map(len, cols.values()))} cards, unchanged → {dest}")
        return
    path.write_text(text)
    print(f"✓ {sum(map(len, cols.values()))} cards → {dest}")

if "--no-promote" not in sys.argv:
    from promote import add_missing_ideas, auto_promote
    add_missing_ideas(env)
    auto_promote(env)

for b in BOARDS:
    sync(*b)
