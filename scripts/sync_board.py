#!/usr/bin/env python3
"""Mirror the GitHub Project 'Tallyn Board' into docs/05 Board/Board.md (Obsidian Kanban format).

GitHub is the source of truth, so this overwrites Board.md. Needs the gh CLI and scripts/board.env
(written by setup_github.sh). Usage: python3 scripts/sync_board.py
"""
import json, pathlib, subprocess, sys, datetime

ROOT = pathlib.Path(__file__).resolve().parent.parent
COLUMNS = ["Ideas", "Backlog", "In Progress", "Review", "Done"]

env = dict(l.split("=", 1) for l in (ROOT / "scripts/board.env").read_text().split() if "=" in l)
out = subprocess.run(
    ["gh", "project", "item-list", env["BOARD_NUMBER"], "--owner", env["BOARD_OWNER"],
     "--format", "json", "--limit", "500"],
    capture_output=True, text=True)
if out.returncode:
    sys.exit(out.stderr)

cols = {c: [] for c in COLUMNS}
for it in json.loads(out.stdout).get("items", []):
    stage = next((v for k, v in it.items() if k.lower() == "stage"), None) or "Ideas"
    c = it.get("content") or {}
    num = f"#{c['number']} " if c.get("number") else ""
    title = (c.get("title") or it.get("title") or "untitled").replace("[", "(").replace("]", ")")
    labels = " ".join("#" + l.replace(":", "/") for l in it.get("labels", []) or [])
    link = f"[{num}{title}]({c['url']})" if c.get("url") else title
    cols.setdefault(stage, []).append(f"- [{'x' if stage == 'Done' else ' '}] {link} {labels}".rstrip())

lines = ["---", "", "kanban-plugin: board", "", "---", "",
         f"<!-- Generated by scripts/sync_board.py on {datetime.date.today()} — edit on GitHub, not here -->", ""]
for col, cards in cols.items():
    lines += [f"## {col}", ""] + (["**Complete**"] if col == "Done" else []) + cards + ["", ""]
lines += ["%% kanban:settings", "```",
          '{"kanban-plugin":"board","list-collapse":[false,false,false,false,true]}', "```", "%%", ""]
dest = ROOT / "docs/05 Board/Board.md"
dest.write_text("\n".join(lines))
print(f"✓ {sum(map(len, cols.values()))} cards → {dest.relative_to(ROOT)}")
